// Copies the Supabase browser build into the renderer and writes renderer/config.js
// from ~/.claude/.env, so the key never sits in the repo. Runs on npm install and before builds.
const fs = require('fs');
const path = require('path');
const os = require('os');

const root = path.join(__dirname, '..');
const vendor = path.join(root, 'renderer', 'vendor');
fs.mkdirSync(vendor, { recursive: true });
fs.copyFileSync(
  path.join(root, 'node_modules', '@supabase', 'supabase-js', 'dist', 'umd', 'supabase.js'),
  path.join(vendor, 'supabase.js')
);

const env = { ...process.env };
const envFile = path.join(os.homedir(), '.claude', '.env');
if (fs.existsSync(envFile)) {
  for (const line of fs.readFileSync(envFile, 'utf8').split('\n')) {
    const m = line.match(/^([A-Z0-9_]+)=(.*)$/);
    if (m && !env[m[1]]) env[m[1]] = m[2];
  }
}
const url = env.CONTENG_SUPABASE_URL;
const key = env.CONTENG_SUPABASE_PUBLISHABLE_KEY;
if (!url || !key) {
  console.error('Set CONTENG_SUPABASE_URL and CONTENG_SUPABASE_PUBLISHABLE_KEY in ~/.claude/.env');
  process.exit(1);
}
fs.writeFileSync(
  path.join(root, 'renderer', 'config.js'),
  `// Generated by tools/vendor.js. Do not commit.\nwindow.CONTENG_CONFIG = ${JSON.stringify({ url, key })};\n`
);
console.log('vendor: supabase.js + config.js ready');
